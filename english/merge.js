// node merge.js — applies patch/*.json into data/*.js (why/alts/gap/qwhy)
const fs=require('fs'),path=require('path');
let stats={files:0,why:0,alts:0,gap:0,qwhy:0,bad:[]};
for (const pf of fs.readdirSync('patch').filter(f=>f.endsWith('.json'))){
  const df='data/'+pf.replace('.json','.js'); if(!fs.existsSync(df)){stats.bad.push('nofile '+df);continue;}
  const patch=JSON.parse(fs.readFileSync('patch/'+pf,'utf8'));
  const calls=[]; global.addUnits=(l,u)=>calls.push([l,u]);
  delete require.cache[path.resolve(df)]; require(path.resolve(df));
  for (const [,units] of calls) for (const u of units) for (const ls of u.lessons){
    const p=patch[ls.id]; if(!p) { stats.bad.push('nopatch '+ls.id); continue; }
    (ls.sents||[]).forEach((s,i)=>{
      if (p.gap && p.gap[i]){ const alts=p.gap[i].split('|'); const cur=(s[0].match(/\[([^\]]+)\]/)||[])[1];
        if (cur && alts[0].trim().toLowerCase()===cur.split('|')[0].trim().toLowerCase()){ s[0]=s[0].replace(/\[[^\]]+\]/,'['+alts.join('|')+']'); stats.gap++; } else stats.bad.push('gapmismatch '+ls.id+':'+i); }
      if (p.why && p.why[i]){ s[2]=p.why[i]; stats.why++; } else if(!s[2]) s[2]='';
      if (p.alts && p.alts[i] && p.alts[i].length){ s[3]=p.alts[i]; stats.alts++; }
    });
    if (p.qwhy && p.qwhy.length){ ls.qwhy=p.qwhy; stats.qwhy++; }
  }
  const out='/* generated by merge.js from reviewed content */\n'+calls.map(([l,u])=>`addUnits(${JSON.stringify(l)}, ${JSON.stringify(u,null,1)});`).join('\n')+'\n';
  fs.writeFileSync(df,out); stats.files++;
}
console.log(JSON.stringify({...stats,bad:stats.bad.length,badSample:stats.bad.slice(0,8)}));
