// node merge2.js — applies patch/enrich-*.json (tags, extra) into data/*.js
const fs=require('fs'),path=require('path'); let st={files:0,tags:0,extra:0,bad:[]};
for (const pf of fs.readdirSync('patch').filter(f=>/^enrich-.*\.json$/.test(f))){
  const df='data/'+pf.replace(/^enrich-/,'').replace('.json','.js'); const patch=JSON.parse(fs.readFileSync('patch/'+pf,'utf8'));
  const calls=[]; global.addUnits=(l,u)=>calls.push([l,u]); delete require.cache[path.resolve(df)]; require(path.resolve(df));
  for (const [,units] of calls) for (const u of units) for (const ls of u.lessons){ const p=patch[ls.id]; if(!p){ st.bad.push('no '+ls.id); continue; }
    if (p.tags) { ls.tags=p.tags; st.tags++; }
    if (p.extra){ ls.extra=p.extra.filter(x=>Array.isArray(x)&&(String(x[0]).match(/\[/g)||[]).length===1); st.extra+=ls.extra.length; if(ls.extra.length<p.extra.length) st.bad.push('dropped '+ls.id); } }
  fs.writeFileSync(df,'/* generated by merge.js from reviewed content */\n'+calls.map(([l,u])=>`addUnits(${JSON.stringify(l)}, ${JSON.stringify(u,null,1)});`).join('\n')+'\n'); st.files++;
  fs.renameSync('patch/'+pf,'patch/'+pf+'.merged');
}
console.log(JSON.stringify({...st,bad:st.bad.slice(0,10),nbad:st.bad.length}));
